from abc import ABC
from datetime import datetime
from src.utils import idGenerator

class Entity(ABC):
  def __init__(self):
    self._id = idGenerator.generate()
    self._created_at = datetime.now()

  @property
  def id(self) -> int:
    return self._id

  @property
  def created_at(self) -> datetime:
    return self._created_at
